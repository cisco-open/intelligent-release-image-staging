def sha(data):
    return hashlib.sha256(data).hexdigest()


def encode(value):
    return json.dumps(value, sort_keys=True).encode()


def tar_bytes(files, *, extra=None):
    stream = io.BytesIO()
    with tarfile.open(fileobj=stream, mode='w') as archive:
        for name, data in sorted(files.items()):
            info = tarfile.TarInfo(name)
            info.mode, info.size = 0o644, len(data)
            archive.addfile(info, io.BytesIO(data))
        if extra is not None:
            archive.addfile(extra)
    return stream.getvalue()


def archive(path, root, files, *, xz=False):
    data = tar_bytes({root + '/' + name: value for name, value in files.items()})
    path.write_bytes(lzma.compress(data) if xz else gzip.compress(data, mtime=0))


def observed(path, data):
    return {'path': path, 'type': 'file', 'sha256': sha(data), 'size': len(data),
            'source_attribution': 'unresolved', 'mode': 0o644}


