@pytest.mark.parametrize('kind', ['gzip-footer', 'gzip-tail', 'xz-footer', 'xz-tail', 'traversal', 'link', 'duplicate'])
def test_source_archives_are_closed_bounded_and_never_extract_links(fixture, kind):
    path = fixture.pool / (subject.PYTHON_ARCHIVE if kind.startswith('xz') else subject.PIP_ARCHIVE)
    if kind.endswith('footer'):
        path.write_bytes(path.read_bytes()[:-5])
    elif kind.endswith('tail'):
        path.write_bytes(path.read_bytes() + (lzma.compress(b'foreign payload') if kind.startswith('xz') else gzip.compress(b'foreign payload')))
    else:
        files = {'pip-25.0.1/' + name: data for name, data in fixture.pip.items()}
        info = tarfile.TarInfo('../escape' if kind == 'traversal' else 'pip-25.0.1/LICENSE.txt' if kind == 'duplicate' else 'pip-25.0.1/alias')
        info.mode = 0o644
        if kind == 'link':
            info.type, info.linkname = tarfile.SYMTYPE, 'LICENSE.txt'
        path.write_bytes(gzip.compress(tar_bytes(files, extra=info)))
    if kind.startswith('xz'):
        repin_python(fixture)
    else:
        fixture.pip_digest = sha(path.read_bytes())
    with pytest.raises(InstallError):
        build(fixture)
    assert not fixture.output.exists()


