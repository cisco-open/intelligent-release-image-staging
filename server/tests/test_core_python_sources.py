def build(fixture, output=None):
    return subject.build_sources(fixture.inventory, fixture.digest, fixture.configs, fixture.pool,
                                 output or fixture.output, pip_sdist_sha256=fixture.pip_digest)


def validate(fixture):
    return subject.validate_source_archive(fixture.output, fixture.inventory, fixture.digest,
                                           fixture.configs, pip_sdist_sha256=fixture.pip_digest)


def change_inventory(fixture, change):
    value = json.loads(fixture.inventory.read_bytes())
    change(value)
    fixture.inventory.write_bytes(encode(value))
    fixture.digest = sha(fixture.inventory.read_bytes())


def change_config(fixture, change, *, roles=subject.ROLES):
    for role in roles:
        value = json.loads(fixture.configs[role].read_bytes())
        change(value)
        fixture.configs[role].write_bytes(encode(value))
        change_inventory(fixture, lambda inventory: inventory['images'][role].update(
            config_digest='sha256:' + sha(fixture.configs[role].read_bytes())))


def repin_python(fixture):
    digest = sha((fixture.pool / subject.PYTHON_ARCHIVE).read_bytes())
    change_config(fixture, lambda v: v['config'].update(Env=['PYTHON_VERSION=3.12.15', 'PYTHON_SHA256=' + digest]))


def rewrite(fixture, change):
    with tarfile.open(fixture.output, 'r:gz') as archive:
        files = {item.name: archive.extractfile(item).read() for item in archive}
    manifest = json.loads(files.pop(subject.MANIFEST))
    change(manifest, files)
    manifest['files'] = {name: shared._record(data) for name, data in files.items()}
    files[subject.MANIFEST] = shared._canonical(manifest)
    fixture.output.write_bytes(gzip.compress(tar_bytes(files), mtime=0))


def test_deterministic_archive_and_independent_validation(fixture):
    first = build(fixture)
    second = build(fixture, fixture.output.with_name('again.tar.gz'))
    assert first['sha256'] == second['sha256'] and not first['authenticated']
    manifest = validate(fixture)
    assert manifest['pip']['authority'] == 'external-caller-sdist-pin'
    assert manifest['cpython']['authority'] == 'external-image-configuration-pin'
    assert manifest['source_coverage_complete'] is False and manifest['rebuild_verified'] is False
    for role in subject.ROLES:
        classes = [row['classification'] for row in manifest['observed_files'][role]]
        assert classes.count('pip-source-data-exact') == 3
        assert 'generated-bytecode-not-compared' in classes
        assert 'installed-dist-info-not-compared' in classes
        assert 'cpython-configuration-pin-only' in classes
        assert 'cpython-version-header-exact' in classes
    assert 'sources/' + subject.PIP_ARCHIVE in manifest['files']
    assert 'notices/pip/src/pip/_vendor/LICENSE.extra' in manifest['files']
    assert 'notices/pip/src/pip/_vendor/dependency.LICENSE' in manifest['files']
    assert 'notices/cpython/PC/crtlicense.txt' in manifest['files']
    assert not list(fixture.output.parent.glob('.iris-core-python-publish-*'))


