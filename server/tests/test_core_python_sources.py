def test_parent_substitution_preserves_owner_files(fixture, monkeypatch):
    parent = fixture.output.parent / 'publication'
    parent.mkdir(mode=0o700)
    fixture.output = parent / 'result.tar.gz'
    original = subject.inspect_source_archive
    def substitute(*args, **kwargs):
        result = original(*args, **kwargs)
        parent.rename(parent.with_name('moved'))
        parent.mkdir(mode=0o700)
        (parent / 'sentinel').write_bytes(b'owner')
        return result
    monkeypatch.setattr(subject, 'inspect_source_archive', substitute)
    with pytest.raises(InstallError, match='directory changed'):
        build(fixture)
    assert (parent / 'sentinel').read_bytes() == b'owner' and not fixture.output.exists()


def test_cli_requires_external_pip_pin_and_verifies(fixture):
    build(fixture)
    cli = Path(__file__).resolve().parents[2] / 'tools/build-core-python-sources.py'
    args = [sys.executable, str(cli), '--inventory', str(fixture.inventory), '--inventory-sha256', fixture.digest,
            '--server-config', str(fixture.configs['server-image']), '--console-config', str(fixture.configs['console-image']),
            '--verify-bundle', str(fixture.output)]
    missing = subprocess.run(args, capture_output=True, text=True)
    assert missing.returncode == 2 and '--pip-sdist-sha256' in missing.stderr
    args += ['--pip-sdist-sha256', fixture.pip_digest]
    valid = subprocess.run(args, capture_output=True, text=True)
    assert valid.returncode == 0 and json.loads(valid.stdout)['source_coverage_complete'] is False
    fixture.output.write_bytes(fixture.output.read_bytes()[:-5])
    invalid = subprocess.run(args, capture_output=True, text=True)
    assert invalid.returncode == 1 and 'Traceback' not in invalid.stderr
