"""Pinned core CPython/pip sources and original notices, without executing code."""

from contextlib import ExitStack
from email.parser import BytesHeaderParser
import gzip
import hashlib
import io
import os
from pathlib import Path, PurePosixPath
import re
import secrets
import tarfile
import tempfile
