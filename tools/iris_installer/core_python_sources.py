from . import image_components as images, offline_inputs as custody
from . import offline_sources as shared, release_kit as kit
from .state import InstallError


PYTHON_VERSION = '3.12.15'
PIP_VERSION = '25.0.1'
SCHEMA = 'iris-core-python-sources-v1'
MANIFEST = 'source-manifest.json'
ROLES = ('console-image', 'server-image')
PYTHON_ARCHIVE = 'Python-' + PYTHON_VERSION + '.tar.xz'
PIP_ARCHIVE = 'pip-' + PIP_VERSION + '.tar.gz'
PREFIX = 'usr/local/lib/python3.12/site-packages/'
MAX_COMPRESSED = 64 * 1024**2
MAX_EXPANDED = 256 * 1024**2
MAX_FILE = 32 * 1024**2
MAX_MEMBERS = 16000
MAX_BUNDLE = 256 * 1024**2
README = b'''Core CPython and pip source/notice companion

The external image inventory SHA-256 and exact raw server/Console configuration
bytes bind this companion. configs/ preserves the complete configuration and
build history as evidence, never as executable instructions. Each configuration
must uniquely pin the supported CPython version and source archive SHA-256.
The original CPython source archive and its version header match that pin and
the observed image version header. Generated CPython binaries are configuration-
bound only: their rebuild equivalence has not been established.

The original pip sdist is bound to an explicitly external caller-supplied digest.
That digest is not presented as an existing repository or release signature.
Every observed pip source/data file is compared byte-for-byte by SHA-256/size
with src/pip in that sdist. Generated bytecode and installed dist-info records
are classified separately and are not claimed equal to source archive members.
The complete sdist retains vendor sources, extra vendor notices, pyproject.toml
and vendoring policy/build inputs. notices/ copies original source notice bytes;
consult those originals without treating this inventory as legal interpretation.

No source recipe, configuration history, shell command or image was executed.
No rebuild, release authentication, legal approval or complete image source
coverage is claimed. Neutral-image Python/XML, Alpine/Debian system packages,
static helpers, aria2 and web assets remain outside this companion's scope.
'''


def fail(message):
    raise InstallError('Core Python sources: ' + message)


def _digest(data):
    return hashlib.sha256(data).hexdigest()


def _inventory(path, expected):
    kit._sha(expected)
    raw = shared._bytes(path, images.MAX_RECEIPT)
    if _digest(raw) != expected:
        fail('inventory differs from the externally expected digest')
    value = kit._json(raw)
    if (not isinstance(value, dict) or value.get('format') != 'iris-image-component-inventory-v1'
            or value.get('scope') != 'inventory-only' or value.get('authenticated') is not False
            or value.get('source_coverage_complete') is not False or not isinstance(value.get('images'), dict)):
        fail('unsupported externally pinned inventory')
    if not set(ROLES) <= set(value['images']):
        fail('both core image inventories are required')
    return raw, value


def _config(path, image):
    if not isinstance(image, dict) or image.get('platform') != 'linux/amd64':
        fail('only core linux/amd64 images are supported')
    raw = shared._bytes(path, kit.MAX_METADATA)
    if image.get('config_digest') != 'sha256:' + _digest(raw):
        fail('raw configuration differs from the image inventory digest')
    value = kit._json(raw)
    if (not isinstance(value, dict) or value.get('architecture') != 'amd64' or value.get('os') != 'linux'
            or not isinstance(value.get('config'), dict)):
        fail('unsupported raw core image configuration')
    env = value['config'].get('Env')
    if not isinstance(env, list) or len(env) > 1024 or any(not isinstance(item, str) for item in env):
        fail('invalid configuration environment')
    pins = {}
    for key in ('PYTHON_VERSION', 'PYTHON_SHA256'):
        matches = [item.partition('=')[2] for item in env if item.partition('=')[0] == key]
        if len(matches) != 1:
            fail('CPython configuration pin is absent or ambiguous')
        pins[key] = matches[0]
    if pins['PYTHON_VERSION'] != PYTHON_VERSION:
        fail('unsupported CPython configuration version')
    kit._sha(pins['PYTHON_SHA256'])
    layers = image.get('layers')
    if not isinstance(layers, list) or not 1 <= len(layers) <= 1024:
        fail('invalid retained core layers')
    ids = []
    for index, layer in enumerate(layers):
        if not isinstance(layer, dict) or type(layer.get('index')) is not int or layer['index'] != index:
            fail('repeated or unordered layer identity')
        diff = layer.get('diff_id')
        if not isinstance(diff, str) or not diff.startswith('sha256:'):
            fail('invalid layer diffID')
        kit._sha(diff[7:])
        ids.append(diff)
    rootfs, history = value.get('rootfs'), value.get('history')
    if (not isinstance(rootfs, dict) or rootfs.get('type') != 'layers' or rootfs.get('diff_ids') != ids
            or not isinstance(history, list) or len(history) > 8192
            or any(not isinstance(row, dict) or type(row.get('empty_layer', False)) is not bool for row in history)
            or sum(not row.get('empty_layer', False) for row in history) != len(ids)):
        fail('configuration rootfs/history differs from retained layers')
    kit._sha(image.get('archive_sha256'))
    return raw, pins['PYTHON_SHA256'], {'config_digest': image['config_digest'],
        'archive_sha256': image['archive_sha256'], 'history_sha256': _digest(shared._canonical(history)), 'diff_ids': ids}


def _notice(name):
    basename = PurePosixPath(name).name.lower()
    return (basename.startswith(('license', 'licence', 'copying', 'copyright', 'notice'))
            or basename.endswith(('.license', '.licence')) or basename == 'crtlicense.txt')


def _source_archive(path, root, *, xz=False):
    """Read bounded closed source tar members; never extract or execute recipes."""
    raw = shared._bytes(path, MAX_COMPRESSED)
    records, retained, members, total = {}, {}, {}, 0
    try:
        with tempfile.TemporaryFile() as plain:
            if xz:
                expanded = shared._expand_index(raw)
                if len(expanded) > MAX_EXPANDED:
                    fail('source archive exceeds expansion bound')
                plain.write(expanded)
                del expanded
            else:
                with gzip.GzipFile(fileobj=io.BytesIO(raw)) as compressed:
                    custody._copy(compressed, plain, MAX_EXPANDED)
            length = plain.tell()
            plain.seek(0)
            with tarfile.open(fileobj=plain, mode='r:', tarinfo=kit._BoundedTarInfo) as archive:
                for member in archive:
                    name = member.name.rstrip('/') if member.isdir() else member.name
                    images._name(name, directory=member.isdir())
                    if (name in members or len(members) >= MAX_MEMBERS or not (member.isfile() or member.isdir())
                            or not 0 <= member.size <= MAX_FILE or member.isdir() and member.size
                            or name != root and not name.startswith(root + '/')
                            or any(key not in ('path', 'mtime') for key in member.pax_headers)):
                        fail('unsupported source archive member')
                    members[name] = member
                    if member.isdir():
                        continue
                    total += member.size
                    if total > MAX_EXPANDED:
                        fail('source archive exceeds total bound')
                    stream = archive.extractfile(member)
                    relative = name[len(root) + 1:]
                    if (_notice(relative) or relative in ('Include/patchlevel.h', 'PKG-INFO', 'pyproject.toml',
                                                         'docs/html/development/vendoring-policy.rst')):
                        if member.size > 4 * 1024**2:
                            fail('source metadata/notice exceeds bound')
                        data = stream.read()
                        retained[relative] = data
                        records[relative] = shared._record(data)
                    else:
                        digest, size = custody._copy(stream, None, member.size)
                        records[relative] = {'sha256': digest, 'size': size}
                if length % 512 or length - archive.offset < 1024:
                    fail('source archive is not completely terminated')
                plain.seek(archive.offset)
                while tail := plain.read(kit.CHUNK):
                    if tail.strip(b'\0'):
                        fail('source archive contains trailing payload')
            parents = {str(parent) for name in members for parent in PurePosixPath(name).parents if str(parent) != '.'}
            if any(members[name].isfile() for name in parents if name in members):
                fail('source archive traverses a regular file')
        return records, retained
    except (OSError, ValueError, tarfile.TarError, EOFError, zlib.error):
        fail('invalid source archive')


def _observed(image, python_records, pip_records):
    result, python_seen, pip_seen = [], False, False
    for layer in image['layers']:
        observation = layer.get('inventory')
        if not isinstance(observation, dict):
            fail('missing retained layer observations')
        copied, runtime = observation.get('copied_component_files'), observation.get('runtime_metadata')
        if not isinstance(copied, list) or not isinstance(runtime, list) or len(copied) > images.MAX_FILES:
            fail('invalid copied-runtime observations')
        metadata, seen = {}, set()
        for row in runtime:
            if not isinstance(row, dict) or not isinstance(row.get('path'), str) or row['path'] in metadata:
                fail('ambiguous runtime metadata')
            metadata[row['path']] = row
        for row in copied:
            if not isinstance(row, dict) or not isinstance(row.get('path'), str):
                fail('invalid copied file observation')
            name = row['path']
            shared._relative(name)
            if name in seen:
                fail('duplicate copied-runtime file')
            seen.add(name)
            is_pip = name.startswith(PREFIX + 'pip/')
            is_dist = name.startswith(PREFIX + 'pip-')
            is_python = (name.startswith(('usr/local/include/python3.12/', 'usr/local/lib/python3.12/'))
                         and '/site-packages/' not in name or name == 'usr/local/bin/python3.12'
                         or name.startswith('usr/local/lib/libpython3'))
            if not (is_pip or is_dist or is_python):
                continue
            kit._sha(row.get('sha256'))
            if row.get('type') != 'file' or type(row.get('size')) is not int or not 0 <= row['size'] <= MAX_FILE:
                fail('unsupported copied core runtime file')
            identity = {'path': name, 'sha256': row['sha256'], 'size': row['size'],
                        'layer': layer['index'], 'diff_id': layer['diff_id']}
            if is_pip:
                relative = name[len(PREFIX):]
                if name.endswith(('.pyc', '.pyo')):
                    identity['classification'] = 'generated-bytecode-not-compared'
                else:
                    source_name = 'src/' + relative
                    if pip_records.get(source_name) != {'sha256': row['sha256'], 'size': row['size']}:
                        fail('pip source/data differs from the pinned sdist: ' + name)
                    identity.update(classification='pip-source-data-exact', source=source_name)
                    pip_seen = True
            elif is_dist:
                if not name.startswith(PREFIX + 'pip-' + PIP_VERSION + '.dist-info/'):
                    fail('unsupported pip installation metadata path')
                identity['classification'] = 'installed-dist-info-not-compared'
                if name.endswith('/METADATA'):
                    item = metadata.get(name, {})
                    if (item.get('component') != 'python-distribution' or item.get('name') != 'pip'
                            or item.get('version') != PIP_VERSION or item.get('sha256') != row['sha256']):
                        fail('observed pip identity is unsupported or inconsistent')
            else:
                identity['classification'] = 'cpython-configuration-pin-only'
                if name == 'usr/local/include/python3.12/patchlevel.h':
                    item = metadata.get(name, {})
                    if (item.get('component') != 'cpython' or item.get('version') != PYTHON_VERSION
                            or item.get('sha256') != row['sha256']
                            or python_records.get('Include/patchlevel.h') != {'sha256': row['sha256'], 'size': row['size']}):
                        fail('observed CPython version header differs from the pinned source')
                    identity.update(classification='cpython-version-header-exact', source='Include/patchlevel.h')
                    python_seen = True
            result.append(identity)
    if not python_seen or not pip_seen or not any(row['path'] == PREFIX + 'pip-' + PIP_VERSION + '.dist-info/METADATA' for row in result):
        fail('core image lacks supported CPython/pip identity evidence')
    return sorted(result, key=lambda row: (row['layer'], row['path']))


def _assemble(raw, inventory, configs, pool, pip_digest, payload, directory, guard):
    kit._sha(pip_digest)
    kit._keys(configs, set(ROLES))
    files, bindings, python_pins = {}, {}, set()
    for role in ROLES:
        config, pin, binding = _config(configs[role], inventory['images'][role])
        shared._write(directory, 'configs/' + role + '.json', config, files)
        python_pins.add(pin)
        bindings[role] = binding
    if len(python_pins) != 1:
        fail('core images disagree on the CPython source pin')
    python_digest = python_pins.pop()
    for name, digest in ((PYTHON_ARCHIVE, python_digest), (PIP_ARCHIVE, pip_digest)):
        record = shared._copy(pool / name, directory, 'sources/' + name, files, maximum=MAX_COMPRESSED)
        if record['sha256'] != digest:
            fail('source archive differs from its external configuration/caller pin')
    guard()
    python_records, python_data = _source_archive(payload / 'sources' / PYTHON_ARCHIVE, 'Python-' + PYTHON_VERSION, xz=True)
    pip_records, pip_data = _source_archive(payload / 'sources' / PIP_ARCHIVE, 'pip-' + PIP_VERSION)
    header = python_data.get('Include/patchlevel.h', b'')
    versions = re.findall(rb'^#define\s+PY_VERSION\s+"([0-9.]+)"\s*$', header, re.M)
    if versions != [PYTHON_VERSION.encode()]:
        fail('CPython source version header is absent or ambiguous')
    metadata = BytesHeaderParser().parsebytes(pip_data.get('PKG-INFO', b''))
    if metadata.get_all('Name') != ['pip'] or metadata.get_all('Version') != [PIP_VERSION]:
        fail('pip sdist identity is absent or ambiguous')
    if not {'pyproject.toml', 'docs/html/development/vendoring-policy.rst'} <= set(pip_records):
        fail('pip build/vendoring inputs are missing')
    observed = {role: _observed(inventory['images'][role], python_records, pip_records) for role in ROLES}
    notices = []
    for component, values in (('cpython', python_data), ('pip', pip_data)):
        for name, data in sorted(values.items()):
            if _notice(name):
                target = 'notices/' + component + '/' + name
                shared._write(directory, target, data, files)
                notices.append({'component': component, 'source': name, 'path': target})
    if not any(row['component'] == 'cpython' for row in notices) or not any(row['component'] == 'pip' for row in notices):
        fail('original source notices are missing')
    shared._write(directory, 'image-components.json', raw, files)
    shared._write(directory, 'README.txt', README, files)
    guard()
    return {'schema': SCHEMA, 'inventory_sha256': _digest(raw), 'scope': 'core-cpython-pip-only',
            'source_coverage_complete': False, 'rebuild_verified': False, 'bindings': bindings,
            'cpython': {'version': PYTHON_VERSION, 'archive': 'sources/' + PYTHON_ARCHIVE,
                        'sha256': python_digest, 'authority': 'external-image-configuration-pin'},
            'pip': {'version': PIP_VERSION, 'archive': 'sources/' + PIP_ARCHIVE,
                    'sha256': pip_digest, 'authority': 'external-caller-sdist-pin'},
            'observed_files': observed, 'notices': notices, 'files': files}


def inspect_source_archive(path, *, expected_inventory_sha256=None, destination=None):
    """Check one bounded closed companion; independent authority is separate."""
    fd, before = kit._open(Path(path), MAX_BUNDLE)
    try:
        with os.fdopen(os.dup(fd), 'rb') as raw, tempfile.TemporaryFile() as plain:
            with gzip.GzipFile(fileobj=raw) as stream:
                custody._copy(stream, plain, MAX_BUNDLE)
            length = plain.tell()
            plain.seek(0)
            members, actual, manifest = {}, {}, None
            with tarfile.open(fileobj=plain, mode='r:', tarinfo=kit._BoundedTarInfo) as archive, ExitStack() as extraction:
                for member in archive:
                    name = shared._relative(member.name)
                    if (not member.isfile() or name in members or len(members) >= MAX_MEMBERS
                            or not 0 <= member.size <= max(MAX_COMPRESSED, images.MAX_RECEIPT)
                            or member.mode != 0o644 or member.uid or member.gid or member.mtime
                            or any(key != 'path' for key in member.pax_headers)):
                        fail('unsupported companion member')
                    if name == MANIFEST:
                        if member.size > images.MAX_RECEIPT:
                            fail('oversized companion manifest')
                        data = archive.extractfile(member).read()
                        manifest, actual[name] = kit._json(data), shared._record(data)
                    else:
                        digest, size = custody._copy(archive.extractfile(member), None, member.size)
                        actual[name] = {'sha256': digest, 'size': size}
                    members[name] = member
                if length % 512 or length - archive.offset < 1024:
                    fail('companion is not completely terminated')
                plain.seek(archive.offset)
                while tail := plain.read(kit.CHUNK):
                    if tail.strip(b'\0'):
                        fail('companion contains trailing payload')
                kit._keys(manifest, {'schema', 'inventory_sha256', 'scope', 'source_coverage_complete', 'rebuild_verified',
                                     'bindings', 'cpython', 'pip', 'observed_files', 'notices', 'files'})
                if (manifest['schema'] != SCHEMA or manifest['scope'] != 'core-cpython-pip-only'
                        or manifest['source_coverage_complete'] is not False or manifest['rebuild_verified'] is not False):
                    fail('unsupported companion scope or coverage claim')
                kit._sha(manifest['inventory_sha256'])
                if expected_inventory_sha256 is not None and manifest['inventory_sha256'] != expected_inventory_sha256:
                    fail('companion belongs to another inventory')
                if {name: row for name, row in actual.items() if name != MANIFEST} != manifest['files']:
                    fail('companion has missing, altered or unlisted files')
                if destination is not None:
                    directory = extraction.enter_context(custody._new_directory(Path(destination)))
                    for name, member in members.items():
                        with custody._output_file(directory, name) as output:
                            digest, size = custody._copy(archive.extractfile(member), output, member.size)
                        if actual[name] != {'sha256': digest, 'size': size}:
                            fail('companion changed during extraction')
                if kit._identity(before) != kit._identity(os.fstat(fd)):
                    fail('companion changed during inspection')
            return manifest
    except (OSError, ValueError, tarfile.TarError, EOFError, zlib.error):
        fail('invalid source companion archive')
    finally:
        os.close(fd)


def validate_source_archive(archive, inventory, expected_inventory_sha256, configs, *, pip_sdist_sha256):
    """Recompute all claims from independent inventory/configuration/source pins."""
    raw, value = _inventory(inventory, expected_inventory_sha256)
    kit._sha(pip_sdist_sha256)
    work = Path('/tmp') / ('iris-core-python-verify-' + secrets.token_hex(16))
    with custody._new_directory(work, remove=True) as held:
        extracted = work / 'extracted'
        manifest = inspect_source_archive(archive, expected_inventory_sha256=expected_inventory_sha256, destination=extracted)
        payload = work / 'verified'
        with custody._new_directory(payload) as directory:
            expected = _assemble(raw, value, configs, extracted / 'sources', pip_sdist_sha256,
                                 payload, directory, lambda: custody._same_directory(work, held))
            if shared._canonical(manifest) != shared._canonical(expected):
                fail('manifest differs from independently verified source/notice evidence')
        custody._same_directory(work, held)
        return manifest


def build_sources(inventory, expected_inventory_sha256, configs, source_pool, output, *, pip_sdist_sha256):
    """Publish deterministic local source/notice evidence, never a trusted release."""
    raw, value = _inventory(inventory, expected_inventory_sha256)
    kit._sha(pip_sdist_sha256)
    pool, output = kit._path(Path(source_pool)), kit._path(Path(output))
    parent = kit._protected_directory(output.parent)
    work = Path('/tmp') / ('iris-core-python-sources-' + secrets.token_hex(16))
    try:
        if output.exists() or output.is_symlink():
            fail('refusing to replace existing companion')
        with custody._new_directory(work, remove=True) as held:
            payload = work / 'payload'
            with custody._new_directory(payload) as directory:
                manifest = _assemble(raw, value, configs, pool, pip_sdist_sha256, payload, directory,
                                     lambda: custody._same_directory(work, held))
                data = shared._canonical(manifest)
                if len(data) > images.MAX_RECEIPT:
                    fail('manifest exceeds bound')
                with custody._output_file(directory, MANIFEST) as stream:
                    stream.write(data)
                stage = output.parent / ('.iris-core-python-publish-' + secrets.token_hex(16))
                with custody._new_directory(stage, remove=True) as stage_fd:
                    with custody._output_file(stage_fd, 'candidate.tar.gz') as stream:
                        with gzip.GzipFile(filename='', mode='wb', fileobj=stream, mtime=0) as compressed:
                            with tarfile.open(fileobj=compressed, mode='w', format=tarfile.PAX_FORMAT) as archive:
                                for name in sorted([MANIFEST, *manifest['files']]):
                                    info = tarfile.TarInfo(name)
                                    info.mode = 0o644
                                    info.size = len(data) if name == MANIFEST else manifest['files'][name]['size']
                                    with (payload / name).open('rb') as source:
                                        archive.addfile(info, source)
                        stream.flush()
                        os.fsync(stream.fileno())
                    candidate = stage / 'candidate.tar.gz'
                    inspect_source_archive(candidate, expected_inventory_sha256=expected_inventory_sha256)
                    custody._same_directory(work, held)
                    custody._same_directory(payload, directory)
                    custody._same_directory(output.parent, parent)
                    custody._same_directory(stage, stage_fd)
                    digest = shared._bytes(candidate, MAX_BUNDLE)
                    os.chmod('candidate.tar.gz', 0o644, dir_fd=stage_fd, follow_symlinks=False)
                    os.link('candidate.tar.gz', output.name, src_dir_fd=stage_fd, dst_dir_fd=parent, follow_symlinks=False)
                    os.fsync(parent)
                return {'archive': str(output), 'sha256': _digest(digest), 'inventory_sha256': expected_inventory_sha256,
                        'manifest_sha256': _digest(data), 'scope': 'core-cpython-pip-only',
                        'authenticated': False, 'source_coverage_complete': False}
    finally:
        os.close(parent)
